// Excluded-hospital reason codes → text.
export function reasonText(code, lang, capLabel) {
  const [kind, cap] = code.split(':');
  const en = {
    too_far: 'too far', er_diverting: 'emergency is diverting patients (full)',
    not_available: `no ${capLabel(cap, 'en')}`, equipment_down: `${capLabel(cap, 'en')} not working now`,
    specialist_off_duty: `${capLabel(cap, 'en')} not on duty now`, all_in_use: `all ${capLabel(cap, 'en')}s in use`,
    children_only: 'children only', maternity_only: 'maternity only',
  };
  const hi = {
    too_far: 'बहुत दूर', er_diverting: 'इमरजेंसी भरी है (मरीज़ दूसरी जगह भेज रहे हैं)',
    not_available: `${capLabel(cap, 'hi')} नहीं`, equipment_down: `${capLabel(cap, 'hi')} अभी ख़राब`,
    specialist_off_duty: `${capLabel(cap, 'hi')} अभी ड्यूटी पर नहीं`, all_in_use: `सभी ${capLabel(cap, 'hi')} उपयोग में`,
    children_only: 'केवल बच्चों के लिए', maternity_only: 'केवल प्रसूति',
  };
  if (kind.startsWith('no_') && kind.endsWith('_bed')) {
    const b = kind.slice(3, -4).toUpperCase();
    return lang === 'hi' ? `कोई ${b} बेड खाली नहीं` : `no ${b} bed free`;
  }
  return (lang === 'hi' ? hi : en)[kind] || code;
}
